#!/usr/bin/env python3
"""Generates the Catalan game over title for LANG_CA=1:

  gengameover.py OUT [--vanilla]   ca/game_over_title.inc: sCaGameOverTitleGfx and
                                   sCaGameOverTitleTileTable (--vanilla: nothing, for the
                                   self-test)

translation/ca/screens/game_over_title.png is the title's background layer (BG1) as it shows on
screen: 256 px wide (the 240 of the screen, and 16 off screen), indexed with row 0 of
menus/game_over/palette.pal, whose colours 4 to 9 the game animates. It is cut into 8x8 tiles;
empty tiles stay the tilemap's 0, like in the vanilla menus/game_over/text.tt, and equal tiles
are stored once.

The game loads menus/game_over/text_and_background (768 tiles, the last 128 being the vanilla
"GAME OVER") at VRAM 0x4000, and the prompt at 0xA800 (tile 832). In the German slot,
translation/ca/include/ca/game_over.h then loads these tiles over the vanilla title, from tile
640 (TILE_BASE), and this tilemap over text.tt: the title can use 192 tiles, the vanilla 128
and the 64 free ones before the prompt. The other languages load neither.
"""
import argparse
import sys
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gfx  # noqa: E402

PNG = gfx.CA / "screens" / "game_over_title.png"
TILE_BASE, MAX_TILES = 640, 192          # 0x9000 to 0xA800, with the layer's tiles at 0x4000
MAP_W = MAP_H = 32                       # a 256x256 background


def cut(img):
    """(tiles, tilemap): the unique non-empty 4bpp tiles and the layer's 32x32 entries."""
    w, h = img.size
    if img.mode != "P" or w != MAP_W * 8 or h % 8 or h > MAP_H * 8:
        sys.exit(f"error: {PNG.name} must be an indexed PNG, {MAP_W * 8} px wide and a multiple of 8 tall")
    px = img.load()
    tiles, tilemap = {}, [0] * (MAP_W * MAP_H)
    for cy in range(h // 8):
        for cx in range(MAP_W):
            pixels = [px[cx * 8 + x, cy * 8 + y] for y in range(8) for x in range(8)]
            if max(pixels) > 15:
                sys.exit(f"error: {PNG.name} uses colours past its 16-colour palette row")
            if not any(pixels):
                continue
            tile = bytes(pixels[i] | pixels[i + 1] << 4 for i in range(0, 64, 2))
            tilemap[cy * MAP_W + cx] = TILE_BASE + tiles.setdefault(tile, len(tiles))
    if len(tiles) > MAX_TILES:
        sys.exit(f"error: {PNG.name} needs {len(tiles)} tiles, but only {MAX_TILES} fit before the prompt's")
    return list(tiles), tilemap


def array(name, data):
    lz = gfx.lz77_optimal(data)
    lz += b"\0" * (-len(lz) % 4)
    words = ",".join(f"{int.from_bytes(lz[i:i + 4], 'little')}u" for i in range(0, len(lz), 4))
    return f"const u32 {name}[] = {{\n    {words}\n}};\n"


def generate():
    if not PNG.exists():
        sys.exit(f"error: {PNG.relative_to(gfx.ROOT)} is missing (tools/gfx_game_over_title.py composes it)")
    tiles, tilemap = cut(Image.open(PNG))
    return (f"// {PNG.relative_to(gfx.ROOT)}: {len(tiles)} tiles (of {MAX_TILES}), from tile {TILE_BASE}\n"
            + array("sCaGameOverTitleGfx", b"".join(tiles)) + "\n"
            + array("sCaGameOverTitleTileTable", b"".join(e.to_bytes(2, "little") for e in tilemap)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--vanilla", action="store_true")
    a = ap.parse_args()
    text = "" if a.vanilla else generate()
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(f"// Generated by translation/ca/tools/gengameover.py. Do not edit.\n{text}", encoding="utf-8")


if __name__ == "__main__":
    main()
