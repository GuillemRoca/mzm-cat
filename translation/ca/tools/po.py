#!/usr/bin/env python3
"""Exports the Catalan text to a gettext .po file for Poedit, and imports it back.

  po.py export [OUT]            write OUT (default translation/ca/build/mzm-cat-ca.po)
  po.py import PO [--dry-run]   write PO's translations into translation/ca/text/*.txt and its
                                comments into the notes of translations.csv; then recompute
                                the centring GAPs (gap.py fix), lint, and regenerate the CSV

One entry per text ID of src/data/text_data.c (all five categories, in pointer-table order):
context = the ID, source = the English, translation = the Catalan. The Spanish (the reference
the Catalan is modelled on, catext.REFERENCE), where the text appears and its line limits are
extracted comments (Poedit's sidebar); the translator comment is the CSV's notes column for
that ID, so notes written in Poedit come back into the CSV.
Line breaks (\\n in text/*.txt) are real line breaks in Poedit. The game's codes stay visible
and must be kept: {COLOR(n)}, {INDENT(n)}, buttons like {A_button}. The {GAP(n)} at the start of a
line centres it and is recomputed on import, so its number needn't be touched. Graphics strings
aren't here: they are drawn into images (tools/gfx_*.py).
Entries left empty in Poedit keep the text they have; entries marked "Needs work" (fuzzy) are
imported and listed.
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import catext  # noqa: E402
import review  # noqa: E402

TOOLS = Path(__file__).resolve().parent
DEFAULT_OUT = catext.CA / "build" / "mzm-cat-ca.po"
LIMITS = {
    "message": "At most 2 lines, each within 224 px.",
    "location": "1 line within 224 px.",
    "description": "Lines within 224 px.",
    "story": "No more lines than the shipped languages use; lines within 224 px.",
    "file_screen": "At most 4 lines, each no wider than the shipped text in that box.",
}
HEADER = """\
# Metroid: Zero Mission, Catalan translation (German slot of the EU release).
# Generated by translation/ca/tools/po.py export; import with po.py import.
# Keep the game's codes ({COLOR(5)}, {A_button}, ...); the {GAP(n)} at the start of a line is
# recomputed on import. Use ” for quotation marks: the game's charset has no straight quote.
msgid ""
msgstr ""
"Project-Id-Version: mzm-cat\\n"
"Language: ca\\n"
"MIME-Version: 1.0\\n"
"Content-Type: text/plain; charset=UTF-8\\n"
"Content-Transfer-Encoding: 8bit\\n"
"X-Source-Language: en\\n"
"""


def to_display(text):
    """Game text (text/*.txt) -> what Poedit shows: \\n becomes a line break."""
    return text.replace("\\n", "\n")


def from_display(text, ident):
    if "\\" in text:
        raise ValueError(f"{ident}: backslash in the translation (use a line break instead of \\n)")
    if '"' in text:
        raise ValueError(f'{ident}: straight quote " in the translation: use ” (the game has no ")')
    return text.replace("\r\n", "\n").replace("\n", "\\n")


def quote(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t").replace("\n", "\\n") + '"'


def po_string(keyword, s):
    if "\n" not in s:
        return f"{keyword} {quote(s)}"
    parts = s.split("\n")
    segs = [p + "\n" for p in parts[:-1]] + ([parts[-1]] if parts[-1] else [])
    return "\n".join([f'{keyword} ""'] + [quote(p) for p in segs])


def entries():
    """[(category, id, english, spanish, catalan or None, line number)] in pointer-table order."""
    strings, tables = catext.vanilla_text()
    out = []
    for category in catext.CATEGORIES:
        catalan, _ = catext.read_translation(category)
        english = dict(catext.table(tables, "English", category))
        spanish = dict(catext.table(tables, catext.REFERENCE, category))
        for idx, _ in catext.table(tables, "English", category):
            ca = catalan.get(idx)
            out.append((category, idx, strings[english[idx]],
                        strings[spanish[idx]] if idx in spanish else "",
                        ca[0] if ca else None, ca[1] if ca else None))
    return out


def export(out):
    notes = review.read_notes()
    blocks = [HEADER]
    for category, idx, en, es, ca, line in entries():
        lines = [f"# {n}" if n else "#" for n in notes.get((category, idx), "").split("\n") if notes.get((category, idx))]
        spanish = review.plain(es).split("\n")
        lines += [f"#. Spanish: {spanish[0]}"] + [f"#.          {s}" for s in spanish[1:]]
        lines += [f"#. {review.WHERE[category]}. {LIMITS[category]}"]
        if line:
            lines.append(f"#: text/{catext.CATEGORIES[category][1]}:{line}")
        lines.append(f"msgctxt {quote(idx)}")
        lines.append(po_string("msgid", to_display(en)))
        lines.append(po_string("msgstr", to_display(ca) if ca is not None else ""))
        blocks.append("\n".join(lines) + "\n")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(blocks), encoding="utf-8")
    return len(blocks) - 1


def unquote(s):
    s = s.strip()
    if len(s) < 2 or s[0] != '"' or s[-1] != '"':
        raise ValueError(f"expected a quoted string: {s}")
    return re.sub(r'\\(.)', lambda m: {"n": "\n", "t": "\t", '"': '"', "\\": "\\"}.get(m.group(1), m.group(1)),
                  s[1:-1])


def parse(text):
    """[dict(ctxt, id, str, fuzzy, comments)] of a .po file (obsolete #~ entries skipped)."""
    out, cur, field = [], None, None

    def flush():
        if cur and "id" in cur:
            out.append(cur)

    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        try:
            if not line:
                flush()
                cur, field = None, None
                continue
            if cur is None or (field and line.startswith("#")):
                if cur is not None and field:
                    flush()
                cur = cur if cur is not None and not field else {"comments": [], "fuzzy": False}
                field = None
            if line.startswith("#~"):
                continue
            if line.startswith("#,"):
                cur["fuzzy"] |= "fuzzy" in line
            elif line.startswith("#") and (len(line) == 1 or line[1] == " "):
                cur["comments"].append(line[2:])
            elif line.startswith("#"):
                continue
            elif line.startswith('"'):
                if not field:
                    raise ValueError("string without a keyword")
                cur[field] += unquote(line)
            else:
                keyword, _, rest = line.partition(" ")
                field = {"msgctxt": "ctxt", "msgid": "id", "msgstr": "str", "msgstr[0]": "str"}.get(keyword)
                if not field:
                    raise ValueError(f"unknown keyword {keyword}")
                cur[field] = unquote(rest)
        except ValueError as e:
            raise ValueError(f"line {n}: {e}") from None
    flush()
    return out


def import_po(path, dry_run):
    try:
        po = parse(path.read_text(encoding="utf-8"))
    except ValueError as e:
        sys.exit(f"error: {path}: {e}")
    known = {idx: (category, ca, line) for category, idx, _, _, ca, line in entries()}
    notes = review.read_notes()
    edits, appended, fuzzy, empty, problems = {}, {}, [], [], []
    new_notes = dict(notes)
    for e in po:
        idx = e.get("ctxt")
        if idx is None and e["id"] == "":
            continue                                       # header
        if idx not in known:
            problems.append(f"{idx or e['id'][:40]!r}: not a text ID of the game")
            continue
        category, ca, line = known[idx]
        note = "\n".join(e["comments"]).strip()
        if note:
            new_notes[(category, idx)] = note
        else:
            new_notes.pop((category, idx), None)
        if e["fuzzy"]:
            fuzzy.append(idx)
        if e["str"] == "":
            empty.append(idx)
            continue
        try:
            text = from_display(e["str"], idx)
        except ValueError as err:
            problems.append(str(err))
            continue
        if text != ca:
            if line:
                edits.setdefault(category, {})[line] = (idx, ca, text)
            else:
                appended.setdefault(category, []).append((idx, text))
    if problems:
        sys.exit("error: nothing imported:\n  " + "\n  ".join(problems))
    changed = sum(len(v) for v in edits.values()) + sum(len(v) for v in appended.values())
    note_changes = sorted(k[1] for k in set(notes) | set(new_notes)
                          if k[0] in catext.CATEGORIES and notes.get(k) != new_notes.get(k))
    for category in catext.CATEGORIES:
        for line, (idx, old, new) in sorted(edits.get(category, {}).items()):
            print(f"{idx}\n  - {old}\n  + {new}")
        for idx, new in appended.get(category, []):
            print(f"{idx} (new)\n  + {new}")
    print(f"{changed} translations changed, {len(note_changes)} notes changed"
          + (f" ({', '.join(note_changes)})" if note_changes else ""))
    if empty:
        print(f"{len(empty)} left empty in the .po, kept as they are: {', '.join(empty)}")
    if fuzzy:
        print(f"marked Needs work in Poedit (imported anyway): {', '.join(fuzzy)}")
    if dry_run:
        return 0
    for category in catext.CATEGORIES:
        if category not in edits and category not in appended:
            continue
        path_txt = catext.CA / "text" / catext.CATEGORIES[category][1]
        lines = path_txt.read_text(encoding="utf-8").split("\n")
        for line, (idx, _, new) in edits.get(category, {}).items():
            lines[line - 1] = f'{idx} = "{new}"'
        for idx, new in appended.get(category, []):
            if lines and lines[-1] == "":
                lines.insert(len(lines) - 1, f'{idx} = "{new}"')
            else:
                lines.append(f'{idx} = "{new}"')
        path_txt.write_text("\n".join(lines), encoding="utf-8")
    if changed:
        subprocess.run([sys.executable, str(TOOLS / "gap.py"), "fix"], check=True)
    review.OUT.write_text(review.render(new_notes), encoding="utf-8")
    lint = subprocess.run([sys.executable, str(TOOLS / "lint.py")])
    if lint.returncode:
        print("lint found problems: fix them in Poedit and import again, or edit text/*.txt",
              file=sys.stderr)
    return lint.returncode


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    e = sub.add_parser("export")
    e.add_argument("out", nargs="?", type=Path, default=DEFAULT_OUT)
    i = sub.add_parser("import")
    i.add_argument("po", type=Path)
    i.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    if a.cmd == "export":
        n = export(a.out)
        print(f"wrote {a.out} ({n} entries)")
        return 0
    return import_po(a.po, a.dry_run)


if __name__ == "__main__":
    sys.exit(main())
