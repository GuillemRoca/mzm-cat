#!/usr/bin/env python3
"""Font patch for LANG_CA=1: glyph overlay on the extracted EU font, and width overrides.

  font.py widths OUTPUT        sCharacterWidths EU initializer with font/widths.txt applied
  font.py build OUTPUT         data/text_characters.gfx with every font/glyphs/XXXX.png on top,
                               written as an include (same format as the extractor's .inc)
  font.py export ID PNG        the vanilla glyph ID (hex) as an editable indexed PNG
  --vanilla (widths, build)    ignore the Catalan overrides (CA_SELFTEST)

Glyph layout (TextDrawCharacter, src/text.c): glyph `id` is two stacked 4bpp tiles, top at
id*32 and bottom at id*32 + 0x400; glyphs wider than 8 px also use id+1. A glyph PNG is
8x16 (or 16x16) and indexed: 0 = background, 1-3 = shading, 4-7 = ink (recoloured by
{COLOR(n)}). Keep each glyph's outline inside its width + 1 column, like the vanilla font.
"""
import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import catext  # noqa: E402

FONT = catext.ROOT / "data" / "text_characters.gfx"
GLYPHS = catext.CA / "font" / "glyphs"
GBAGFX = catext.CA / "build" / "gbagfx"
FONT_SIZE = 0x2C000

# Editing palette (BGR555): background, three shades, then ink.
PALETTE = [(16, 16, 40), (90, 90, 110), (140, 140, 160), (200, 200, 210)] + [(255, 255, 255)] * 12


def gbapal(colours):
    out = bytearray()
    for r, g, b in colours:
        v = (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)
        out += v.to_bytes(2, "little")
    return bytes(out)


def glyph_tiles(cid, wide):
    """Byte offsets of a glyph's tiles in PNG tile order (row-major, 1 or 2 tiles wide)."""
    cols = 2 if wide else 1
    return [(cid + c) * 32 + r * 0x400 for r in (0, 1) for c in range(cols)]


def gbagfx(*args):
    subprocess.run([str(GBAGFX), *map(str, args)], check=True)


def cmd_widths(out, vanilla=False):
    w = catext.widths(catalan=not vanilla)
    rows = [", ".join(str(v) for v in w[i:i + 16]) for i in range(0, len(w), 16)]
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text("// Generated by translation/ca/tools/font.py from font/widths.txt. Do not edit.\n    "
                         + ",\n    ".join(rows) + "\n")


def cmd_build(out, vanilla=False):
    font = bytearray(FONT.read_bytes())
    if len(font) != FONT_SIZE:
        sys.exit(f"error: {FONT} is {len(font)} bytes, expected {FONT_SIZE}")
    w = catext.widths(catalan=True)
    with tempfile.TemporaryDirectory() as tmp:
        for png in [] if vanilla else sorted(GLYPHS.glob("*.png")):
            cid = int(png.stem, 16)
            raw = Path(tmp) / f"{png.stem}.4bpp"
            gbagfx(png, raw)
            data = raw.read_bytes()
            offs = glyph_tiles(cid, w[cid] > 8 if cid < len(w) else True)
            if len(data) != 32 * len(offs):
                sys.exit(f"error: {png} must be {8 * (len(offs) // 2)}x16 px (width {w[cid]})")
            for i, off in enumerate(offs):
                font[off:off + 32] = data[i * 32:(i + 1) * 32]
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text(",".join(f"{b}u" for b in font))


def cmd_export(cid_hex, png):
    cid = int(cid_hex, 16)
    w = catext.widths(catalan=False)
    wide = cid >= len(w) or w[cid] > 8
    font = FONT.read_bytes()
    with tempfile.TemporaryDirectory() as tmp:
        raw, pal = Path(tmp) / "g.4bpp", Path(tmp) / "g.gbapal"
        raw.write_bytes(b"".join(font[o:o + 32] for o in glyph_tiles(cid, wide)))
        pal.write_bytes(gbapal(PALETTE))
        gbagfx(raw, png, "-palette", pal, "-width", 2 if wide else 1)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("widths", "build"):
        s = sub.add_parser(name)
        s.add_argument("output")
        s.add_argument("--vanilla", action="store_true", help="ignore the Catalan overrides")
    e = sub.add_parser("export")
    e.add_argument("id")
    e.add_argument("png")
    a = ap.parse_args()
    if a.cmd == "widths":
        cmd_widths(a.output, a.vanilla)
    elif a.cmd == "build":
        cmd_build(a.output, a.vanilla)
    else:
        cmd_export(a.id, a.png)
