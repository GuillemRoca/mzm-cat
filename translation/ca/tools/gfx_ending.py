#!/usr/bin/env python3
"""Composes the Catalan ending graphics from the five vanilla EU sheets.

  gfx_ending.py OUT_DIR   (needs data/ extracted and build/gbagfx)

ending/text_spanish (OBJ tiles from 0x80):
  rows 0-1, 2-3   the two typed result lines, drawn whole: TEMPS TOTAL DE JOC and OBJECTES
                  ACONSEGUITS, from the sheet's alphabet (rows 4-7) at the positions of
                  ending_layout.py, so the whole line matches the typed letters.
  rows 8-10       the last line, Fins a la propera missió! (descenders in row 10), from the
                  letters of the other languages' last lines (English has another font) (cut by their fill shapes with the
                  file select composer); F, which none has, is drawn in DRAWN_F.
ending/numbers_misc_spanish: the "new record" box. The bottom line RÉCORD! becomes RÈCORD!
(the accent mirrored); the top tab, sized to its word, is rebuilt for NOU from the Italian
NUOVO tab (its edges, and the letters N, O and U with their spacing), centred like the others.
Sprites placing these lines are generated by genending.py from the same layout and this PNG.
Writes OUT_DIR/text_spanish.png and OUT_DIR/numbers_misc_spanish.png.
"""
import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ending_layout  # noqa: E402
import gfx_file_select as fs  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
GBAGFX = ROOT / "translation" / "ca" / "build" / "gbagfx"
LANGS = fs.LANGS
LINE_ROWS = {"ClearTime": 0, "Collecting": 16}
LAST = (64, 88)                      # rows of the last line, descenders included
# the Italian sheet has one more line (PERCENTUALE), so its last line starts at tile 0x1c0;
# the letters come from the four languages after English (English is in another font)
LAST_TOP = {"italian": 80}
LAST_VANILLA = ["See you next mission!", "Bis zur nächsten Mission!", "A la prochaine mission!",
                "Alla prossima missione!", "¡Hasta la próxima misión!"]
LAST_CATALAN = "Fins a la propera missió!"
# F in the last line's font (fill 1, highlight 2, outline 3), from the H's stem and bar;
# rows 3-15 of the line (cap height at row 3, like the H)
DRAWN_F = [
    "333333333",
    "311222223",
    "311111113",
    "311333333",
    "31133333.",
    "31122223.",
    "31111113.",
    "31133333.",
    "3113.....",
    "3113.....",
    "3113.....",
    "3113.....",
    "3333....."]


def load(name, lang, tmp):
    raw, png, pal = (Path(tmp) / f"{name}_{lang}.{e}" for e in ("4bpp", "png", "gbapal"))
    pal.write_bytes((ROOT / "data/ending/image_text.pal").read_bytes()[:32])
    subprocess.run([GBAGFX, ROOT / f"data/ending/{name}_{lang}.gfx.lz", raw], check=True)
    subprocess.run([GBAGFX, raw, png, "-palette", pal, "-width", "32"], check=True)
    im = Image.open(png)
    im.load()
    return im


def tile_xy(tile):
    t = tile - 0x80
    return (t % 32) * 8, (t // 32) * 8


def typed_lines(img):
    layout, _ = ending_layout.ending()
    src = img.copy()
    for key, top in LINE_ROWS.items():
        line = layout[key]
        for x in range(img.width):
            for y in range(top, top + 16):
                img.putpixel((x, y), 0)
        for ch, x, _, dims, tile in line["letters"]:
            sx, sy = tile_xy(tile)
            w = ending_layout.WIDTH[dims]
            for dx in range(w):
                for dy in range(16):
                    v = src.getpixel((sx + dx, sy + dy))
                    if v:
                        img.putpixel((x - line["start"] + dx, top + dy), v)
        print(f"{key:10} {line['text']!r}: {line['width']} px from x = {line['start']}")


def last_line(img, sheets):
    h = LAST[1] - LAST[0]
    # lenient: lines where two letters touch (German, French) are skipped
    fs.ASSETS["last_line"] = dict(band=h, body=range(3, 16), outline={0, 3}, slots={"line": (0, 0, 256)}, left=0,
                                  lenient=True)
    # the English line is in another font, 2 px higher: an empty text skips its sheet
    fs.VANILLA["last_line"] = {"line": [""] + LAST_VANILLA[1:]}
    fs.CATALAN["last_line"] = {"line": LAST_CATALAN}
    fs.DRAWN[("last_line", "F")] = ["." * 9] * 3 + DRAWN_F + ["." * 9] * (h - 3 - len(DRAWN_F))
    crops = {lang: im.crop((0, LAST_TOP.get(lang, LAST[0]), im.width, LAST_TOP.get(lang, LAST[0]) + h))
             for lang, im in sheets.items()}
    glyphs, spacing = fs.harvest(crops, "last_line")
    line = fs.compose("last_line", crops, glyphs, spacing)
    img.paste(line, (0, LAST[0]))


def record_box(sheets):
    """NOU / RÈCORD! from the Spanish box (bottom) and the Italian tab (top)."""
    es, it = sheets["spanish"], sheets["italian"]
    img = es.copy()
    e0, e1 = runs(es, range(11, 17), 176, 232)[1]        # R, É, C, O, R, D, !
    # top tab: the Italian tab's edges around its N, O and U (NUOVO)
    tl, tr = tab_edges(it)
    n, u, o, _, last = runs(it, range(2, 8), tl, tr + 1)  # N U O V O
    letters = list(range(*n)) + list(range(*o)) + list(range(*u))
    edges_l, edges_r = list(range(tl, n[0])), list(range(last[1], tr + 1))
    est_l, est_r = tab_edges(es)
    centre = (est_l + est_r) / 2
    # the accent reaches row 9, so the tab must cover it: pad the tab with background columns
    pad = 0
    while round(centre - (len(edges_l + letters + edges_r) + 2 * pad - 1) / 2) > e0 - 2:
        pad += 1
    cols = edges_l + [n[0] - 1] * pad + letters + [n[0] - 1] * pad + edges_r
    left = round(centre - (len(cols) - 1) / 2)
    right = left + len(cols) - 1
    box_l, box_r = 176, 231
    for x in range(box_l, box_r + 1):
        for y in range(0, 9):
            img.putpixel((x, y), 0)
        # row 9: the box's top edge, open under the tab
        if box_l + 2 < x < box_r and not left <= x <= right:
            img.putpixel((x, 9), 7)
    for i, sx in enumerate(cols):
        for y in range(0, 10):
            img.putpixel((left + i, y), it.getpixel((sx, y)))
    # bottom line: the É accent (rows 9-10, over the letters of rows 11-16) mirrored, with its
    # shading (5 right of the stroke, 6 below right) redone
    stroke = [(x, y) for x in range(e0, e1) for y in (9, 10) if es.getpixel((x, y)) in (1, 2, 3)]
    for x in range(e0, e1):
        for y in (9, 10):
            if es.getpixel((x, y)) in (1, 2, 3, 5, 6):
                img.putpixel((x, y), 4)
    grave = [(e0 + e1 - 1 - x, y) for x, y in stroke]
    for x, y in grave:
        img.putpixel((x, y), es.getpixel((e0 + e1 - 1 - x, y)))
    for x, y in grave:
        for sx, sy, v in ((x + 1, y, 5), (x + 1, y + 1, 6)):
            if sy <= 10 and (sx, sy) not in grave and img.getpixel((sx, sy)) == 4:
                img.putpixel((sx, sy), v)
    print(f"record box: NOU tab x = {left}..{right}, RÈCORD! with a grave accent")
    return img


def runs(im, rows, x0, x1):
    """Column runs with letter fill (1-3) in the given rows, each with its shadow column."""
    out, x = [], x0
    def fill(x):
        return any(im.getpixel((x, y)) in (1, 2, 3) for y in rows)
    while x < x1:
        if fill(x):
            s = x
            while x < x1 and fill(x):
                x += 1
            out.append([s, x + 1])
        else:
            x += 1
    return out


def tab_edges(im):
    """First and last column of the top tab (its border on row 0)."""
    xs = [x for x in range(170, 240) if im.getpixel((x, 0)) != 0]
    return xs[0], xs[-1]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out_dir")
    a = ap.parse_args()
    out = Path(a.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        text = {lang: load("text", lang, tmp) for lang in LANGS}
        nums = {lang: load("numbers_misc", lang, tmp) for lang in LANGS}
    img = text["spanish"].copy()
    typed_lines(img)
    last_line(img, text)
    img.save(out / "text_spanish.png")
    record_box(nums).save(out / "numbers_misc_spanish.png")


if __name__ == "__main__":
    main()
